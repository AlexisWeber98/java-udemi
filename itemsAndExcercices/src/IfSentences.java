public class IfSentences {
    public static void main(String[] args) {
        int age = 11;

        if (age >= 18) {
            System.out.println("You are an adult.");
        } else if (age >= 13) {
            System.out.println("You are minor");

        } else {
            System.out.println("You are a child.");
        }
    }

    // --------------------------------------------------------//
}
